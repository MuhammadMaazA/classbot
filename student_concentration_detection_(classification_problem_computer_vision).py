def create_image_dataframe(data_dir):
    """
    Create a pandas DataFrame with image paths and corresponding class labels.

    Args:
        data_dir (str): The root directory containing subdirectories for each class.

    Returns:
        pd.DataFrame: A DataFrame with columns 'Image_Path' and 'Class_Label'.
    """
    image_paths = []
    class_labels = []

    # Walk through the directory and its subdirectories
    for class_label in os.listdir(data_dir):
        class_dir = os.path.join(data_dir, class_label)
        for subclass_label in os.listdir(class_dir):
          subclass_dir = os.path.join(class_dir, subclass_label)
          print(subclass_label)
          if os.path.isdir(subclass_dir):
              # Get a list of image files in the class directory
              images = [f for f in os.listdir(subclass_dir) if f.lower().endswith(('.jpg'))]

              # Add the image paths and class label to the lists
              image_paths.extend([os.path.join(subclass_dir, img) for img in images])
              class_labels.extend([str(class_label)+"_"+str(subclass_label)] * len(images))

    # Create a DataFrame
    image_df = pd.DataFrame({'Image_Path': image_paths, 'Class_Label': class_labels})

    return image_df

